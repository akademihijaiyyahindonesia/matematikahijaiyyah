#!/usr/bin/env python3
"""jamrah_board.py -- the jamrah gate, all 256 bytes, on the board.

    python3 rtl/scripts/jamrah_board.py /dev/tty.usbserial-X   # the board
    python3 rtl/scripts/jamrah_board.py                          # the interpreter

The board must be running loader.hasm. The owner's first validation lab, 20
September 2026: the gate's input is one byte, so its whole input space is 256
values, and the answer is absolute -- 256 of 256, or a defect.

-- one definition, not two -----------------------------------------------
The program sent to the board is GENERATED from rtl/programs/jamrah_gate.hasm,
not retyped: its body -- every instruction between the opening `MOVI R1, <byte>`
and the closing `HALT` -- is copied verbatim into a loop over R0 = 0..255. The
gate the board runs is therefore the gate that file defines, instruction for
instruction; a second transcription could drift and still agree with itself.

The answers are held against rtl/tb/jamrah_vectors.txt, the same 256 lines that
rtl/tb/tb_hijaiyyah_jamrah_gate.v checks the RTL gate against. One reference
for the silicon gate and the program gate alike.

-- what it checks, per byte -----------------------------------------------
The pulse (1..28 names a letter) AND all seven internal nodes of the tree,
n0..n6. The root alone is the popcount, and a popcount can come out right with
the tree's internals wrong -- the RTL bench checks every node for that reason,
and so does this.

-- what it times ---------------------------------------------------------
A first pass over the 256 bytes, with no printing in it, between two reads of
the free-running counter at 0xFF4. On the board that counter counts CLOCKS; in
the interpreter it counts INSTRUCTIONS. The number is reported with its unit,
and the two are never compared. The pass includes the loop's own four
instructions per byte (MOV, ADDI, CMPI, JNE), and says so.

-- what it cannot reach -------------------------------------------------
rtl/hijaiyyah_jamrah_gate.v on the board. Inside the Ka'bah slot its outputs
are left unconnected (`.gate_pulse ()` in hijaiyyah_kabah_gowin_top.v), so the
silicon gate cannot be observed from the board without changing RTL, which is
the owner's decision. Its 256/256 is a SIMULATION result.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "rtl" / "scripts"))

from hijaiyyah.core.master_table import MASTER_TABLE  # noqa: E402
from hijaiyyah.hisa.assembler import assemble  # noqa: E402
from hijaiyyah.hisa.machine import HISAMachine  # noqa: E402

GATE = ROOT / "rtl" / "programs" / "jamrah_gate.hasm"
VECTORS = ROOT / "rtl" / "tb" / "jamrah_vectors.txt"
LOAD_BASE = 64          # loader.hasm writes the program here and enters it
PER_BYTE = 9            # byte, pulse, n0 .. n6
LOOP_OVERHEAD = 4       # MOV, ADDI, CMPI, JNE per byte in the timed pass


def gate_body(source: str) -> list[str]:
    """The instructions between the opening MOVI R1 and the closing HALT."""
    lines = source.splitlines()
    code = [i for i, ln in enumerate(lines)
            if ln.split(";")[0].strip()]
    first, last = code[0], code[-1]
    head = lines[first].split(";")[0].split()
    tail = lines[last].split(";")[0].split()
    if head[:2] != ["MOVI", "R1,"] or tail != ["HALT"]:
        raise ValueError("jamrah_gate.hasm no longer opens with MOVI R1 and "
                         "ends with HALT; the generator must be revisited")
    body = lines[first + 1:last]
    if any("R0" in ln.split(";")[0].replace(",", " ").split() for ln in body):
        raise ValueError("the gate body uses R0, which the loop counts with")
    if any(ln.split(";")[0].strip().endswith(":") or
           (":" in ln.split(";")[0]) for ln in body):
        raise ValueError("the gate body has a label; copying it twice would collide")
    return body


def sweep_program(source: str) -> str:
    body = "\n".join(gate_body(source))
    return f"""; GENERATED by rtl/scripts/jamrah_board.py from rtl/programs/jamrah_gate.hasm.
; Do not edit: the body is that file's, verbatim, twice.

        MOVI  R5, 0
        LOAD  R2, R5, 0xFF4         ; counter before the timed pass
        STORE R2, R5, 0x100
        MOVI  R0, 0
t_loop: MOV   R1, R0
{body}
        ADDI  R0, R0, 1
        CMPI  R0, 256
        JNE   t_loop
        MOVI  R5, 0
        LOAD  R2, R5, 0xFF4         ; counter after it
        LOAD  R3, R5, 0x100
        SUB   R2, R2, R3
        PRINT R2                    ; the timed pass, in the counter's unit

        MOVI  R0, 0
p_loop: MOV   R1, R0
{body}
        PRINT R1                    ; the byte
        PRINT R3                    ; the pulse
        PRINT R6                    ; n0
        PRINT R7                    ; n1
        PRINT R8                    ; n2
        PRINT R9                    ; n3
        PRINT R10                   ; n4
        PRINT R11                   ; n5
        PRINT R2                    ; n6, the root
        ADDI  R0, R0, 1
        CMPI  R0, 256
        JNE   p_loop
        HALT
"""


def reference() -> list[tuple[int, ...]]:
    """rtl/tb/jamrah_vectors.txt: byte(hex) pulse n0..n5 n6(hex)."""
    rows = []
    for ln in VECTORS.read_text().split("\n"):
        f = ln.split()
        if len(f) != PER_BYTE:
            continue
        rows.append((int(f[0], 16), int(f[1]), *(int(x) for x in f[2:8]),
                     int(f[8], 16)))
    if len(rows) != 256:
        raise ValueError(f"{VECTORS} holds {len(rows)} rows, not 256")
    return rows


def compare(values: list[int]) -> tuple[int, list[str]]:
    """The printed values after the timing word, against the reference."""
    want = reference()
    got = [tuple(values[i:i + PER_BYTE]) for i in range(0, len(values), PER_BYTE)]
    bad: list[str] = []
    for i, w in enumerate(want):
        g = got[i] if i < len(got) else None
        if g != w:
            bad.append(f"byte {i:#04x}: got {g}, want {w}")
    return len(want) - len(bad), bad


def run_interpreter(program: str) -> list[int]:
    m = HISAMachine(MASTER_TABLE)
    m.load_program(assemble(program))
    m.run()
    return list(m.output)


RAW_DUMP = Path("/tmp/jamrah_board_raw.bin")


def parse(raw: bytes) -> tuple[list[int], int, list[bytes]]:
    """Lines of digits -> values; non-printing bytes dropped; other lines kept aside.

    Measured on the board, 20 September 2026: one run lost its FIRST line -- the
    timing word -- and every group after it slid one value, while the raw capture
    of the very next run was clean. WHY it was lost is not proven. So nothing is
    lost quietly any more: non-printing bytes are dropped and COUNTED, a line that
    is still not digits is returned as REJECTED, and the whole capture is written
    to RAW_DUMP, so the next occurrence names its own cause.
    """
    values: list[int] = []
    rejected: list[bytes] = []
    dropped = 0
    for ln in raw.split(b"\n"):
        body = ln.rstrip(b"\r")
        kept = bytes(c for c in body if 32 <= c < 127)
        dropped += len(body) - len(kept)
        text = kept.decode("ascii").strip()
        if text.isdigit():
            values.append(int(text))
        elif text:
            rejected.append(body)
    return values, dropped, rejected


def run_board(port: str, program: str,
              timeout_s: float = 30.0) -> tuple[list[int], int, list[bytes]]:
    import serial  # pyserial, optional
    from send_program import encode
    stream = encode(assemble(program, base=LOAD_BASE))
    raw = bytearray()
    with serial.Serial(port, 115200, timeout=0.2) as link:
        link.reset_input_buffer()
        link.write(stream)
        link.flush()
        deadline = time.time() + timeout_s
        while b"CYCLES=" not in raw and time.time() < deadline:
            raw += link.read(4096)
        raw += link.read(64)            # the rest of the CYCLES line
    RAW_DUMP.write_bytes(bytes(raw))
    return parse(bytes(raw.split(b"CYCLES=")[0]))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("port", nargs="?", help="serial device; omit to use the interpreter")
    args = ap.parse_args(argv)

    program = sweep_program(GATE.read_text(encoding="utf-8"))
    dropped, rejected = 0, []
    if args.port:
        values, dropped, rejected = run_board(args.port, program)
    else:
        values = run_interpreter(program)
    if not values:
        print("nothing came back")
        return 1
    timed, answers = values[0], values[1:]
    agree, bad = compare(answers)
    unit = "clocks" if args.port else "instructions"
    print(f"{agree}/256 bytes agree with {VECTORS.relative_to(ROOT)} "
          f"(pulse and all seven nodes)")
    print(f"timed pass: {timed} {unit} for 256 bytes, "
          f"{timed / 256:.2f} per byte including {LOOP_OVERHEAD} loop instructions")
    if dropped:
        print(f"dropped {dropped} non-printing byte(s) from the wire; raw capture in {RAW_DUMP}")
    for r in rejected[:5]:
        print(f"  rejected line, not a number: {r!r}")
    for b in bad[:10]:
        print("  " + b)
    return 0 if agree == 256 else 1


if __name__ == "__main__":
    raise SystemExit(main())
