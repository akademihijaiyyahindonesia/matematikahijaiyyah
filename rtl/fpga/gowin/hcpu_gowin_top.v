// ============================================================================
// HCPU Gowin FPGA Wrapper — hcpu_gowin_top.v
// Target: Tang Nano 20K (GW2AR-LV18QN88C8/I7)
// (c) 2026 Maulana Amratulloh
// ============================================================================
//
// Board resources:
//   - 27 MHz onboard oscillator
//   - 6 LEDs (active low)
//   - 2 buttons (active low)
//   - UART via USB-C
//
// ── On the clock ────────────────────────────────────────────────────────────
//
// This wrapper used to instantiate a PLL whose body was `assign clkout = clkin`
// with a comment calling it a placeholder, while passing CLK_HZ = 50_000_000
// down to hcpu_top. The core therefore sized CLKS_PER_BIT for 50 MHz and ran at
// 27, putting the UART at 62,212 baud instead of 115,200 — 46% off, far outside
// the 2–3% a receiver tolerates. Nothing would have come out of the serial port
// but noise, and nothing in the design said so.
//
// The frequency is now derived from USE_PLL rather than written down twice, so
// the two cannot disagree again.
//
// USE_PLL = 0 (default) runs straight off the 27 MHz oscillator. Correct,
// verifiable in simulation, and needs no vendor IP.
//
// USE_PLL = 1 expects a Gowin rPLL generated by the IDE's IP generator. Note
// that 50 MHz is not a good target from a 27 MHz reference: 50/27 is already in
// lowest terms, so IDIV+1 must be 27 and the phase detector would run at 1 MHz,
// below the range Gowin's rPLL specifies. 54 MHz — a straight doubling — keeps
// the detector at 27 MHz and is what SYS_HZ assumes. Check the generated
// parameters against the datasheet before trusting the number.
//

`include "hcpu_pkg.vh"

// ============================================================================
// PLACES AND ROUTES on the Tang Nano 20K. Measured 7 September 2026 with
// yosys 0.68 -> nextpnr-himbaechel 0.11.1 -> gowin_pack, GW2AR-LV18QN88C8/I7,
// re-measured 2026-09-13 after `pc_valid` stopped being tied high -- Fetch now
// says whether the PC it presents is a real one, and the trap unit waits when
// it is not:
//
//     LUT4       14,726 / 20,736   71%
//     DFF         4,481 / 15,552   28%
//     BSRAM          17 /     46   36%
//
//     Fmax      120.31 MHz (PASS at the 12.00 MHz constraint), up from
//               115.66 -- taken after routing, not the 95.26 MHz figure
//               nextpnr prints after placement.
//     Bitstream  7,261,470 bytes, gowin_pack exits 0
//
// +12 LUT4 AND +1 DFF IS WHAT THE REPAIR COSTS, and the DFF column is the
// check on it: the change adds exactly one bit of state -- `pc_valid` in
// hcpu_fetch, written in the same places `if_pc` is -- and the twelve LUT4 are
// the gating that bit does. A maskable interrupt used to read Fetch's
// "presenting nothing" as ADDRESS ZERO and save it as the place to resume;
// sixty swept deadlines saved zero twenty-one times, and on the board eight
// samples of trap_shadow.hasm answered 0 0 88 89 88 0 0 88 with the loop at
// 88. kernel.hasm's process A had frozen at 337 that way since the scheduler
// was built. It now runs for as long as the bench watches.
//
// The measurement before it, 2026-09-12, after the codex block -- CMOV, CZERO,
// CEQ, CRHO, CU and CMOD4 landed beside CGET/CSET: 14,714 LUT4 (70%), 4,480
// DFF, Fmax 115.66 MHz.
//
// +483 LUT4 AND +0 DFF IS WHAT THE SIX COST, and the shape of them is why:
// none adds state. CMOV and CZERO are muxes into the codex writeback, CEQ a
// 144-bit comparator feeding one flag bit, CU and CRHO are read out of
// hcpu_guard.v -- which already computes both -- rather than recomputed, and
// CMOD4 is a two-bit slice of component 0. The DFF column not moving at all is
// the check on that, not a coincidence beside it.
//
// SEVEN WERE BUILT AND SIX ARE HERE. CDOT (0x49) was measured on this same
// slot and removed: an inner product over fourteen components is fourteen 8x8
// multipliers, and with them this wrapper reaches 16,015 LUT4 (77%) where
// nextpnr answers "Unable to find legal placement for all cells" -- twice,
// same message, so it is not placer variance. The decision to ship six was the
// owner's; the blocker is named in cosmictera-build/OFF.md, and CDOT still
// runs in the HVM.
//
// THE CRITICAL PATH IS STILL INSIDE EXECUTE, 3.51 ns of logic plus 4.80 ns of
// routing. Neither the 84.26 -> 115.66 rise of the previous run nor the
// 115.66 -> 120.31 of this one was separated into design and placement, and
// neither run claims it. What the run does
// establish: the design still passes the constraint the flow places it
// against, and the board's own clock is 27 MHz.
//
// The block above previously recorded 14,005 / 4,480 / 17 at 118.43 MHz,
// measured 2026-09-10 after the first board bring-up -- the run that made the
// reset synchronous and put a clk_sys heartbeat on LED[5], +27 DFF
// (heartbeat[24:0] and btn_q[1:0]) and +36 LUT4 for the counter and its
// falling-edge detect.
//
// A +2 LUT4 MOVE BETWEEN THE 7 AND 10 SEPTEMBER RUNS IS STILL UNEXPLAINED, and
// no run since has resolved it -- they only move past it. The bisection chain
// below ends at 13,967; the run before the 10 September one measured 13,969
// and could not say why. Two explanations were never separated: an RTL edit
// landing between runs (rtl/hcpu_controller.v's PRINT stall fix is already the
// +22 the chain accounts for), or synthesis not being bit-identical run to
// run. What was established: hcpu_video_timing.v is not the cause -- it is
// pruned before placement. The +36 of that run and the +226 of this one are
// separately accounted for above, and neither absorbs the +2.
//
// The design was not always this large. Bisected, one synthesis run per
// commit -- the lesson is about a commit, and the LUT4 counts are what
// carry it:
//
//     ae83fd2  the toolchain and the first bitstream    6,753
//     096e392  supervisor mode                          6,740
//     348e9c6  the boot path                           13,644
//     e5bd781  one letter is the whole instruction     13,710
//     a606ed5  memory protection                       13,800
//     34ca28c  syscall                                 13,817
//
// One commit did it. The boot path added the loader's write port to
// instruction memory -- three lines, `if (imem_we) imem[imem_waddr] <= ...` --
// and that turned a read-only initialised array into a read-write memory.
// BSRAM went 4 -> 17 and the rest landed in fabric: +5,015 LUT4 and +2,666
// DFF for a port that carries a program in from the wire. The bridge is real
// and its testbench passes; what it costs had simply never been measured,
// and five further commits landed without re-running place and route -- the
// same drift this file already recorded once for the cell count, repeated
// for the routed result. rtl/hcpu_controller.v's later PRINT stall fix
// (rtl/programs/nui_embedding.hasm's own header tells that story) added
// another +22 LUT4, -1 DFF on top: 13,945 -> 13,967. Nowhere near the size
// of the boot path's jump, and irrelevant to whether this fits -- the 20K
// was never close to its own ceiling.
//
// Fingerprint restamped 2026-09-13 WITH a fresh place-and-route run, which is
// the only honest way to restamp it after a design change: the repair touched
// hcpu_fetch.v and hcpu_top.v, so the figures above were re-measured rather
// than carried over. The same was true of the 2026-09-12 stamp for the codex
// block, and the 2026-09-11 stamp for CSET.
// The 2026-09-10 stamp was applied WITHOUT a run, and that was justified
// mechanically rather than by promise: the institution changed (HMCL became a
// research unit under Yayasan Akademi Hijaiyyah Indonesia, and the rights line
// became the inventor personally), rewriting one comment line in every
// fingerprinted source -- reversing only those copyright lines in memory
// reproduced the recorded hash exactly, so the sweep was provably the entire
// delta and no design byte moved.
// RTL FINGERPRINT: d4ef5bb54b889b7e58df87ec3754af0ec1ab4477b25139d7ccb7b511a364102b
//
// The numbers above are pinned to the RTL they describe by a hash of the
// source, not by a date and not by whoever remembers to look. Change any
// file in the fingerprint and tests/test_integrity/test_place_and_route.py
// fails, saying to re-run place and route rather than letting the record and
// the design drift apart again.
//
// -nodsp IS REQUIRED, and the reason is the packer rather than the design.
// synth_gowin infers MULT9X9 from the multiplies in hcpu_codex_alu's squared
// norm and distance as much as from hcpu_mul, nextpnr places them without
// complaint, and gowin_pack then dies on `KeyError: 'IRBY_IREG0BL_0'` -- an
// attribute apycula's chipdb does not carry. The suite's own gowin_pack fails
// identically, so it is not a version mismatch. The cost is measured:
//
//     with DSP     LUT4 4,550 (52%)   Fmax 82.33 MHz
//     -nodsp       LUT4 6,746 (78%)   Fmax 90.14 MHz
//
// +2,196 LUT4 and, unexpectedly, a FASTER clock -- the DSP sat on the critical
// path. Drop the flag when apycula can pack a MULT9X9.
//
module hcpu_gowin_top #(
    parameter USE_PLL = 0,           // 0: run at 27 MHz; 1: use the rPLL
    // 1 infers a MULT9X9, which nextpnr places happily and gowin_pack then
    // refuses: `KeyError: 'IRBY_IREG0BL_0'`, an attribute apycula's chipdb
    // does not carry -- the suite's own gowin_pack fails identically, so it is
    // the packer and not a version mismatch. Shift-add costs LUTs the board
    // has to spare and produces a bitstream, so 0 is the default here and the
    // DSP path stays available for whoever fixes the packer.
    parameter USE_DSP = 0,
    // Which image is baked in. Default is the program; a testbench points it
    // at the loader instead, so the boot path can be proved without a board.
    parameter PROGRAM_HEX = "program.hex",
    parameter BAUD    = 115200
) (
    input  wire        clk_27m,      // 27 MHz onboard oscillator
    input  wire        btn_rst_n,    // Button S2 — active low reset
    input  wire        uart_rxd,     // UART RX ← USB bridge
    output wire        uart_txd,     // UART TX → USB bridge
    output wire [5:0]  led           // 6 LEDs — active low
);

    localparam OSC_HZ = 27_000_000;
    // Single source of truth for the system frequency. hcpu_top sizes the UART
    // divider from this, so it must describe the clock that actually arrives.
    localparam SYS_HZ = (USE_PLL != 0) ? (OSC_HZ * 2) : OSC_HZ;

    wire clk_sys;
    wire pll_locked;

    generate
        if (USE_PLL != 0) begin : g_pll
            // Replace with the Gowin IDE's generated rPLL for 27 → 54 MHz.
            Gowin_rPLL u_pll (
                .clkout (clk_sys),
                .lock   (pll_locked),
                .clkin  (clk_27m)
            );
        end else begin : g_direct
            assign clk_sys    = clk_27m;
            assign pll_locked = 1'b1;
        end
    endgenerate

    // ── Reset synchronizer ──────────────────────────────────────
    // btn_rst_n is pin 87 = MODE1, which this board holds low. Level
    // sensitive and asynchronous, that pinned sys_rst_n at 0 forever: the
    // first bring-up configured and then executed nothing -- zero UART
    // bytes, one LED. PULL_MODE=UP reached the bitstream (verified in the
    // P&R database) and did not lift it, so the board wins the pin.
    // Edge-detected and synchronous, a stuck level costs one pulse instead
    // of a deadlock, and a real press still resets. The initial values
    // matter: without them rst_sync starts X in simulation, where the old
    // async branch used to define it. Simulation drives this pin high and
    // so could never have caught any of it.
    reg [2:0] rst_sync = 3'b000;
    reg [1:0] btn_q    = 2'b00;
    wire      sys_rst_n = rst_sync[2];

    always @(posedge clk_sys) begin
        btn_q <= {btn_q[0], btn_rst_n};
        if (btn_q[1] & ~btn_q[0])
            rst_sync <= 3'b000;
        else
            rst_sync <= {rst_sync[1:0], pll_locked};
    end

    // ── Instruction memory ──────────────────────────────────────
    // BRAM-style registered read with clock enable, matching what
    // hcpu_fetch.v expects: address on cycle N, data on N+1, output held
    // while imem_ce is low.
    reg [`ILEN-1:0] imem [0:`CODE_DEPTH-1];
    wire [`CODE_ADDR_W-1:0] imem_addr;
    wire                    imem_ce;
    reg  [`ILEN-1:0]        imem_data_r;
    wire [`ILEN-1:0]        imem_data;

    integer i;
    initial begin
        // The guard is load-bearing, and this fill is why the first board
        // bring-up executed 4,096 NOPs instead of the program: under yosys,
        // filling the array before $readmemh silently discards the readmemh
        // and every BSRAM INIT word comes out zero. Measured on a 14-line
        // testcase -- fill then readmemh gives 0 init bits and maps to SPX9,
        // readmemh alone gives the program and maps to SP. Nothing looked
        // wrong because OP_NOP is 8'h00, so an emptied memory and a
        // NOP-filled one are the same bits. The board needs no fill at all
        // (BSRAM powers up zeroed, which is already OP_NOP); a simulator
        // does, because an unwritten reg array reads X.
`ifndef YOSYS
        for (i = 0; i < `CODE_DEPTH; i = i + 1)
            imem[i] = {`OP_NOP, 24'h000000};
`endif
        $readmemh(PROGRAM_HEX, imem);
    end

    // The loader's write port. $readmemh still puts a program there at
    // synthesis -- that program is now the LOADER, and what it loads arrives
    // over the wire.
    wire                    imem_we;
    wire [`CODE_ADDR_W-1:0] imem_waddr;
    wire [`ILEN-1:0]        imem_wdata;

    always @(posedge clk_sys)
        if (imem_we) imem[imem_waddr] <= imem_wdata;

    always @(posedge clk_sys) begin
        if (imem_ce)
            imem_data_r <= imem[imem_addr];
    end
    assign imem_data = imem_data_r;

    // ── HCPU core ───────────────────────────────────────────────
    wire halted_out, guard_led_out;
    wire core_txd;

    hcpu_top #(
        .CLK_HZ  (SYS_HZ),
        .BAUD    (BAUD),
        .USE_DSP (USE_DSP)
    ) u_hcpu (
        .clk            (clk_sys),
        .rst_n          (sys_rst_n),
        .imem_addr      (imem_addr),
        .imem_ce        (imem_ce),
        .imem_data      (imem_data),
        .imem_we        (imem_we),
        .imem_waddr     (imem_waddr),
        .imem_wdata     (imem_wdata),
        .uart_rx        (uart_rxd),
        .uart_tx        (core_txd),
        .halted         (halted_out),
        .guard_led      (guard_led_out),
        // Debug port — unused on FPGA, tied off
        .dbg_gpr_raddr  (5'd0),
        .dbg_gpr_rdata  (),
        .dbg_flags      ()
    );

    // ── Cycle counter and its report ────────────────────────────
    //
    // The instruction counts in tools/integrity_benchmark.py are static: they
    // come from reading programs, not running them, and they model no stalls.
    // This measures. The counter runs from reset release to halt, so it
    // includes load-use stalls, store-load stalls and branch flushes — every
    // cycle the pipeline actually spent.
    //
    // The count goes out as hexadecimal, not decimal, on purpose. Decimal
    // needs division by ten, and the divide in hcpu_top's PRINT FSM is
    // already the longest topological path in the design at 86 logic levels.
    // Adding a second one would make the wrapper worse at exactly the thing
    // an Fmax measurement is trying to find. Eight nibbles through a lookup
    // cost nothing.

    reg [31:0] cycle_count;
    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n)
            cycle_count <= 32'd0;
        else if (!halted_out)
            cycle_count <= cycle_count + 32'd1;
    end

    // The core may still be shifting PRINT bytes when halt asserts, because
    // hcpu_top's global_stall freezes the pipeline without waiting for the
    // UART to drain. Taking the line early truncates them.
    //
    // A fixed delay is the wrong instrument for this. The first version
    // waited a constant number of clocks, which was past one byte and not
    // past three — test_bsm.hasm prints "112", and the wrapper cut into the
    // second character. How long to wait depends on how much the program
    // printed, which the wrapper cannot know.
    //
    // So it watches the line instead. A UART idles high; twelve bit times of
    // continuous high is longer than any single frame, so it cannot fall
    // inside one. The threshold is derived from SYS_HZ and BAUD rather than
    // written down, for the same reason SYS_HZ itself is derived.

    localparam IDLE_CLKS = (SYS_HZ / BAUD) * 12;
    localparam IDLE_W    = $clog2(IDLE_CLKS + 1);

    reg [IDLE_W-1:0] idle_count;
    reg              report_armed;
    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n) begin
            idle_count   <= {IDLE_W{1'b0}};
            report_armed <= 1'b0;
        end else if (halted_out && !report_armed) begin
            if (!core_txd)
                idle_count <= {IDLE_W{1'b0}};
            else if (idle_count >= IDLE_CLKS[IDLE_W-1:0])
                report_armed <= 1'b1;
            else
                idle_count <= idle_count + 1'b1;
        end
    end

    // "\r\nCYCLES=" + 8 hex digits + "\r\n"  =  19 bytes
    localparam MSG_LEN = 5'd19;

    reg  [4:0] msg_idx;
    reg        msg_start;
    reg        msg_done;
    wire       msg_busy;

    function [7:0] hexchar;
        input [3:0] nibble;
        hexchar = (nibble < 4'd10) ? (8'd48 + {4'd0, nibble})
                                   : (8'd55 + {4'd0, nibble});
    endfunction

    reg [7:0] msg_byte;
    always @(*) begin
        case (msg_idx)
            5'd0:  msg_byte = 8'h0D;
            5'd1:  msg_byte = 8'h0A;
            5'd2:  msg_byte = "C";
            5'd3:  msg_byte = "Y";
            5'd4:  msg_byte = "C";
            5'd5:  msg_byte = "L";
            5'd6:  msg_byte = "E";
            5'd7:  msg_byte = "S";
            5'd8:  msg_byte = "=";
            5'd9:  msg_byte = hexchar(cycle_count[31:28]);
            5'd10: msg_byte = hexchar(cycle_count[27:24]);
            5'd11: msg_byte = hexchar(cycle_count[23:20]);
            5'd12: msg_byte = hexchar(cycle_count[19:16]);
            5'd13: msg_byte = hexchar(cycle_count[15:12]);
            5'd14: msg_byte = hexchar(cycle_count[11:8]);
            5'd15: msg_byte = hexchar(cycle_count[7:4]);
            5'd16: msg_byte = hexchar(cycle_count[3:0]);
            5'd17: msg_byte = 8'h0D;
            default: msg_byte = 8'h0A;
        endcase
    end

    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n) begin
            msg_idx   <= 5'd0;
            msg_start <= 1'b0;
            msg_done  <= 1'b0;
        end else begin
            msg_start <= 1'b0;
            if (report_armed && !msg_done && !msg_busy && !msg_start) begin
                msg_start <= 1'b1;
                if (msg_idx == MSG_LEN - 1)
                    msg_done <= 1'b1;
                else
                    msg_idx <= msg_idx + 5'd1;
            end
        end
    end

    wire report_txd;
    hcpu_uart_tx #(
        .CLK_HZ (SYS_HZ),
        .BAUD   (BAUD)
    ) u_report_tx (
        .clk      (clk_sys),
        .rst_n    (sys_rst_n),
        .tx_data  (msg_byte),
        .tx_start (msg_start),
        .tx_out   (report_txd),
        .tx_busy  (msg_busy)
    );

    // The core owns the line until its output has drained; the report owns it
    // afterwards. Idle is high on a UART, which is what the core holds.
    assign uart_txd = report_armed ? report_txd : core_txd;

    // ── LED mapping (active low) ────────────────────────────────
    // LED[0]: GUARD flag (on = pass)
    // LED[1]: halted (on = stopped)
    // LED[2]: PLL locked
    // LED[3]: reset active
    // LED[5] is a clock heartbeat, and it exists because LED[2] cannot do
    // this job: ~pll_locked is combinational and lights even if clk_sys
    // never ticks, so a held reset and a dead clock look identical on the
    // board. This one blinks only while clk_sys runs -- 0.62 s per toggle
    // at 27 MHz.
    reg [24:0] heartbeat = 25'd0;
    always @(posedge clk_sys) heartbeat <= heartbeat + 1'b1;

    assign led[0] = ~guard_led_out;
    assign led[1] = ~halted_out;
    assign led[2] = ~pll_locked;
    assign led[3] = ~sys_rst_n;
    assign led[4] = ~report_armed;   // cycle report sent
    assign led[5] = heartbeat[24];   // blinking = clk_sys alive

endmodule
