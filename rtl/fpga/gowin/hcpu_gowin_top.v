// ============================================================================
// HCPU Gowin FPGA Wrapper — hcpu_gowin_top.v
// Target: Tang Nano 9K (GW1NR-LV9QN88PC6/I5)
// (c) 2026 HMCL
// ============================================================================
//
// Board resources:
//   - 27 MHz onboard oscillator
//   - 6 LEDs (active low)
//   - 2 buttons (active low)
//   - UART via USB-C
//
// ── On the clock ────────────────────────────────────────────────────────────
//
// This wrapper used to instantiate a PLL whose body was `assign clkout = clkin`
// with a comment calling it a placeholder, while passing CLK_HZ = 50_000_000
// down to hcpu_top. The core therefore sized CLKS_PER_BIT for 50 MHz and ran at
// 27, putting the UART at 62,212 baud instead of 115,200 — 46% off, far outside
// the 2–3% a receiver tolerates. Nothing would have come out of the serial port
// but noise, and nothing in the design said so.
//
// The frequency is now derived from USE_PLL rather than written down twice, so
// the two cannot disagree again.
//
// USE_PLL = 0 (default) runs straight off the 27 MHz oscillator. Correct,
// verifiable in simulation, and needs no vendor IP.
//
// USE_PLL = 1 expects a Gowin rPLL generated by the IDE's IP generator. Note
// that 50 MHz is not a good target from a 27 MHz reference: 50/27 is already in
// lowest terms, so IDIV+1 must be 27 and the phase detector would run at 1 MHz,
// below the range Gowin's rPLL specifies. 54 MHz — a straight doubling — keeps
// the detector at 27 MHz and is what SYS_HZ assumes. Check the generated
// parameters against the datasheet before trusting the number.
//

`include "hcpu_pkg.vh"

// ============================================================================
// PLACE AND ROUTE FAILS AT THIS COMMIT. The design is 159% of the board's
// LUT4 and nextpnr stops with "no BELs remaining to implement cell type
// 'LUT4'". Measured 3 September 2026 with yosys 0.68 -> nextpnr-himbaechel
// 0.11.1, GW1NR-LV9QN88PC6/I5:
//
//     LUT4       13,805 / 8,640   159%    <- does not fit
//     DFF         4,410 / 6,480    68%
//     BSRAM          17 /    26    65%
//
//     Fmax        unmeasured -- routing never completes, so there is no
//                 timing report. The [EH] on Fmax is back.
//
// It used to fit, and the earlier numbers in this header were honest when
// they were written. Re-running the commit they were taken from reproduces
// them: ae83fd2 gives LUT4 6,753 (78%), Fmax 97.94 MHz. What happened is that
// five commits landed afterwards and none of them re-ran place and route --
// the same drift this file already recorded once for the cell count, repeated
// for the routed result.
//
// Bisected, one synthesis run per commit:
//
//     ae83fd2  the toolchain and the first bitstream    6,753   78%   fits
//     096e392  supervisor mode                          6,740   78%   fits
//     348e9c6  the boot path                           13,644  157%   FAILS
//     e5bd781  one letter is the whole instruction     13,710  158%   FAILS
//     a606ed5  memory protection                       13,800  159%   FAILS
//     34ca28c  syscall                                 13,817  159%   FAILS
//
// One commit did it. The boot path added the loader's write port to
// instruction memory -- three lines, `if (imem_we) imem[imem_waddr] <= ...` --
// and that turned a read-only initialised array into a read-write memory.
// BSRAM went 4 -> 17 and the rest landed in fabric: +5,015 LUT4 and +2,666
// DFF for a port that carries a program in from the wire. The bridge is real
// and its testbench passes; what it costs had simply never been measured.
//
// So the board cannot be flashed from this commit, and the per-second figures
// that were resolved by 90.14 MHz are unresolved again until either the
// memory is inferred cleanly or the instruction memory is made smaller.
//
// RTL FINGERPRINT: cbb7370db3ea3798936e5e8945d078f021697abeb343498391a565ec6e4be741
//
// The numbers above are pinned to the RTL they describe by a hash of the
// source, not by a date and not by whoever remembers to look. Change any
// file in the fingerprint and tests/test_integrity/test_place_and_route.py
// fails, saying to re-run place and route rather than letting the record and
// the design drift apart again.
//
// -nodsp IS REQUIRED, and the reason is the packer rather than the design.
// synth_gowin infers MULT9X9 from the multiplies in hcpu_codex_alu's squared
// norm and distance as much as from hcpu_mul, nextpnr places them without
// complaint, and gowin_pack then dies on `KeyError: 'IRBY_IREG0BL_0'` -- an
// attribute apycula's chipdb does not carry. The suite's own gowin_pack fails
// identically, so it is not a version mismatch. The cost is measured:
//
//     with DSP     LUT4 4,550 (52%)   Fmax 82.33 MHz
//     -nodsp       LUT4 6,746 (78%)   Fmax 90.14 MHz
//
// +2,196 LUT4 and, unexpectedly, a FASTER clock -- the DSP sat on the critical
// path. Drop the flag when apycula can pack a MULT9X9.
//
module hcpu_gowin_top #(
    parameter USE_PLL = 0,           // 0: run at 27 MHz; 1: use the rPLL
    // 1 infers a MULT9X9, which nextpnr places happily and gowin_pack then
    // refuses: `KeyError: 'IRBY_IREG0BL_0'`, an attribute apycula's chipdb
    // does not carry -- the suite's own gowin_pack fails identically, so it is
    // the packer and not a version mismatch. Shift-add costs LUTs the board
    // has to spare and produces a bitstream, so 0 is the default here and the
    // DSP path stays available for whoever fixes the packer.
    parameter USE_DSP = 0,
    // Which image is baked in. Default is the program; a testbench points it
    // at the loader instead, so the boot path can be proved without a board.
    parameter PROGRAM_HEX = "program.hex",
    parameter BAUD    = 115200
) (
    input  wire        clk_27m,      // 27 MHz onboard oscillator
    input  wire        btn_rst_n,    // Button S2 — active low reset
    input  wire        uart_rxd,     // UART RX ← USB bridge
    output wire        uart_txd,     // UART TX → USB bridge
    output wire [5:0]  led           // 6 LEDs — active low
);

    localparam OSC_HZ = 27_000_000;
    // Single source of truth for the system frequency. hcpu_top sizes the UART
    // divider from this, so it must describe the clock that actually arrives.
    localparam SYS_HZ = (USE_PLL != 0) ? (OSC_HZ * 2) : OSC_HZ;

    wire clk_sys;
    wire pll_locked;

    generate
        if (USE_PLL != 0) begin : g_pll
            // Replace with the Gowin IDE's generated rPLL for 27 → 54 MHz.
            Gowin_rPLL u_pll (
                .clkout (clk_sys),
                .lock   (pll_locked),
                .clkin  (clk_27m)
            );
        end else begin : g_direct
            assign clk_sys    = clk_27m;
            assign pll_locked = 1'b1;
        end
    endgenerate

    // ── Reset synchronizer ──────────────────────────────────────
    reg [2:0] rst_sync;
    wire      sys_rst_n = rst_sync[2];

    always @(posedge clk_sys or negedge btn_rst_n) begin
        if (!btn_rst_n)
            rst_sync <= 3'b000;
        else
            rst_sync <= {rst_sync[1:0], pll_locked};
    end

    // ── Instruction memory ──────────────────────────────────────
    // BRAM-style registered read with clock enable, matching what
    // hcpu_fetch.v expects: address on cycle N, data on N+1, output held
    // while imem_ce is low.
    reg [`ILEN-1:0] imem [0:`CODE_DEPTH-1];
    wire [`CODE_ADDR_W-1:0] imem_addr;
    wire                    imem_ce;
    reg  [`ILEN-1:0]        imem_data_r;
    wire [`ILEN-1:0]        imem_data;

    integer i;
    initial begin
        // Unwritten words stay NOP, so a short program cannot run into
        // whatever the block RAM powers up holding.
        for (i = 0; i < `CODE_DEPTH; i = i + 1)
            imem[i] = {`OP_NOP, 24'h000000};
        $readmemh(PROGRAM_HEX, imem);
    end

    // The loader's write port. $readmemh still puts a program there at
    // synthesis -- that program is now the LOADER, and what it loads arrives
    // over the wire.
    wire                    imem_we;
    wire [`CODE_ADDR_W-1:0] imem_waddr;
    wire [`ILEN-1:0]        imem_wdata;

    always @(posedge clk_sys)
        if (imem_we) imem[imem_waddr] <= imem_wdata;

    always @(posedge clk_sys) begin
        if (imem_ce)
            imem_data_r <= imem[imem_addr];
    end
    assign imem_data = imem_data_r;

    // ── HCPU core ───────────────────────────────────────────────
    wire halted_out, guard_led_out;
    wire core_txd;

    hcpu_top #(
        .CLK_HZ  (SYS_HZ),
        .BAUD    (BAUD),
        .USE_DSP (USE_DSP)
    ) u_hcpu (
        .clk            (clk_sys),
        .rst_n          (sys_rst_n),
        .imem_addr      (imem_addr),
        .imem_ce        (imem_ce),
        .imem_data      (imem_data),
        .imem_we        (imem_we),
        .imem_waddr     (imem_waddr),
        .imem_wdata     (imem_wdata),
        .uart_rx        (uart_rxd),
        .uart_tx        (core_txd),
        .halted         (halted_out),
        .guard_led      (guard_led_out),
        // Debug port — unused on FPGA, tied off
        .dbg_gpr_raddr  (5'd0),
        .dbg_gpr_rdata  (),
        .dbg_flags      ()
    );

    // ── Cycle counter and its report ────────────────────────────
    //
    // The instruction counts in tools/integrity_benchmark.py are static: they
    // come from reading programs, not running them, and they model no stalls.
    // This measures. The counter runs from reset release to halt, so it
    // includes load-use stalls, store-load stalls and branch flushes — every
    // cycle the pipeline actually spent.
    //
    // The count goes out as hexadecimal, not decimal, on purpose. Decimal
    // needs division by ten, and the divide in hcpu_top's PRINT FSM is
    // already the longest topological path in the design at 86 logic levels.
    // Adding a second one would make the wrapper worse at exactly the thing
    // an Fmax measurement is trying to find. Eight nibbles through a lookup
    // cost nothing.

    reg [31:0] cycle_count;
    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n)
            cycle_count <= 32'd0;
        else if (!halted_out)
            cycle_count <= cycle_count + 32'd1;
    end

    // The core may still be shifting PRINT bytes when halt asserts, because
    // hcpu_top's global_stall freezes the pipeline without waiting for the
    // UART to drain. Taking the line early truncates them.
    //
    // A fixed delay is the wrong instrument for this. The first version
    // waited a constant number of clocks, which was past one byte and not
    // past three — test_bsm.hasm prints "112", and the wrapper cut into the
    // second character. How long to wait depends on how much the program
    // printed, which the wrapper cannot know.
    //
    // So it watches the line instead. A UART idles high; twelve bit times of
    // continuous high is longer than any single frame, so it cannot fall
    // inside one. The threshold is derived from SYS_HZ and BAUD rather than
    // written down, for the same reason SYS_HZ itself is derived.

    localparam IDLE_CLKS = (SYS_HZ / BAUD) * 12;
    localparam IDLE_W    = $clog2(IDLE_CLKS + 1);

    reg [IDLE_W-1:0] idle_count;
    reg              report_armed;
    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n) begin
            idle_count   <= {IDLE_W{1'b0}};
            report_armed <= 1'b0;
        end else if (halted_out && !report_armed) begin
            if (!core_txd)
                idle_count <= {IDLE_W{1'b0}};
            else if (idle_count >= IDLE_CLKS[IDLE_W-1:0])
                report_armed <= 1'b1;
            else
                idle_count <= idle_count + 1'b1;
        end
    end

    // "\r\nCYCLES=" + 8 hex digits + "\r\n"  =  19 bytes
    localparam MSG_LEN = 5'd19;

    reg  [4:0] msg_idx;
    reg        msg_start;
    reg        msg_done;
    wire       msg_busy;

    function [7:0] hexchar;
        input [3:0] nibble;
        hexchar = (nibble < 4'd10) ? (8'd48 + {4'd0, nibble})
                                   : (8'd55 + {4'd0, nibble});
    endfunction

    reg [7:0] msg_byte;
    always @(*) begin
        case (msg_idx)
            5'd0:  msg_byte = 8'h0D;
            5'd1:  msg_byte = 8'h0A;
            5'd2:  msg_byte = "C";
            5'd3:  msg_byte = "Y";
            5'd4:  msg_byte = "C";
            5'd5:  msg_byte = "L";
            5'd6:  msg_byte = "E";
            5'd7:  msg_byte = "S";
            5'd8:  msg_byte = "=";
            5'd9:  msg_byte = hexchar(cycle_count[31:28]);
            5'd10: msg_byte = hexchar(cycle_count[27:24]);
            5'd11: msg_byte = hexchar(cycle_count[23:20]);
            5'd12: msg_byte = hexchar(cycle_count[19:16]);
            5'd13: msg_byte = hexchar(cycle_count[15:12]);
            5'd14: msg_byte = hexchar(cycle_count[11:8]);
            5'd15: msg_byte = hexchar(cycle_count[7:4]);
            5'd16: msg_byte = hexchar(cycle_count[3:0]);
            5'd17: msg_byte = 8'h0D;
            default: msg_byte = 8'h0A;
        endcase
    end

    always @(posedge clk_sys or negedge sys_rst_n) begin
        if (!sys_rst_n) begin
            msg_idx   <= 5'd0;
            msg_start <= 1'b0;
            msg_done  <= 1'b0;
        end else begin
            msg_start <= 1'b0;
            if (report_armed && !msg_done && !msg_busy && !msg_start) begin
                msg_start <= 1'b1;
                if (msg_idx == MSG_LEN - 1)
                    msg_done <= 1'b1;
                else
                    msg_idx <= msg_idx + 5'd1;
            end
        end
    end

    wire report_txd;
    hcpu_uart_tx #(
        .CLK_HZ (SYS_HZ),
        .BAUD   (BAUD)
    ) u_report_tx (
        .clk      (clk_sys),
        .rst_n    (sys_rst_n),
        .tx_data  (msg_byte),
        .tx_start (msg_start),
        .tx_out   (report_txd),
        .tx_busy  (msg_busy)
    );

    // The core owns the line until its output has drained; the report owns it
    // afterwards. Idle is high on a UART, which is what the core holds.
    assign uart_txd = report_armed ? report_txd : core_txd;

    // ── LED mapping (active low) ────────────────────────────────
    // LED[0]: GUARD flag (on = pass)
    // LED[1]: halted (on = stopped)
    // LED[2]: PLL locked
    // LED[3]: reset active
    assign led[0] = ~guard_led_out;
    assign led[1] = ~halted_out;
    assign led[2] = ~pll_locked;
    assign led[3] = ~sys_rst_n;
    assign led[4] = ~report_armed;   // cycle report sent
    assign led[5] = 1'b1;            // off

endmodule
